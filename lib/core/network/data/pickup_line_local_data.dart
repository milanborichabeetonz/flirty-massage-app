import '../models/pickup_line_model.dart';

class PickupLineLocalData {
  PickupLineLocalData._();

  static const String kRandom = 'Random';

  static const List<String> allKnownCategories = [
    'Cute',
    'Cheesy',
    'Dirty',
    'Flirty',
    'Funny',
    'Romantic',
    'Complimentary',
    'Clever',
    'Bad',
    'Nerdy',
    'Food',
    'Hookup',
  ];

  static const Map<String, List<String>> _lines = {
    'Cute': _cuteLines,
    'Cheesy': _cheesyLines,
    'Dirty': _dirtyLines,
    'Flirty': _flirtyLines,
    'Funny': _funnyLines,
    'Romantic': _romanticLines,
    'Complimentary': _complimentaryLines,
    'Clever': _cleverLines,
    'Bad': _badLines,
    'Nerdy': _nerdyLines,
    'Food': _foodLines,
    'Hookup': _hookupLines,
  };

  static List<String> linesForCategory(String category) {
    final key = category.trim().toLowerCase();
    for (final entry in _lines.entries) {
      if (entry.key.trim().toLowerCase() == key) {
        return List<String>.unmodifiable(entry.value);
      }
    }
    return const <String>[];
  }

  static List<PickupLineModel> modelsForCategory(String category) {
    final raw = linesForCategory(category);
    if (raw.isEmpty) return const <PickupLineModel>[];
    return raw
        .map((t) => PickupLineModel(text: t, category: category))
        .toList(growable: false);
  }
}

